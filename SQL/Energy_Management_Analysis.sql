/* ============================================================
   SMART ENERGY MANAGEMENT & COST OPTIMIZATION SYSTEM
   Database: MySQL

   Purpose:
   Store and analyze:
   1. Store information
   2. Daily energy/resource readings
   3. Monthly electricity utility bills

   Database design:
   
                    stores
                   /      \
                  /        \
                 /          \
      energy_readings     utility_bills

   Relationship:
   stores 1 ---- N energy_readings
   stores 1 ---- N utility_bills

   ============================================================ */


/* ============================================================
   STEP 1: CREATE DATABASE
   ============================================================ */

CREATE DATABASE IF NOT EXISTS energy_management;

-- Select the database
USE energy_management;


/* ============================================================
   STEP 2: CREATE STORES TABLE
   ============================================================

   This table stores basic information about each store.

   Example:
   store_id     = 101
   store_name   = Store 101
   city         = Bengaluru
   area_sqft    = 5000

   Primary Key:
   store_id

   ============================================================ */

CREATE TABLE IF NOT EXISTS stores (

    -- Unique ID for every store
    store_id INT PRIMARY KEY,

    -- Name of the store
    store_name VARCHAR(100) NOT NULL,

    -- City where the store is located
    city VARCHAR(50) NOT NULL,

    -- State where the store is located
    state VARCHAR(50) NOT NULL,

    -- Type/category of store
    store_type VARCHAR(50) NOT NULL,

    -- Store area in square feet
    area_sqft DECIMAL(10,2) NOT NULL,

    -- Average operating hours per day
    operating_hours DECIMAL(4,2) NOT NULL,

    -- Date when the store opened
    opening_date DATE NOT NULL,

    -- Whether the store is currently active
    active BOOLEAN NOT NULL DEFAULT TRUE,

    -- Area cannot be zero or negative
    CONSTRAINT chk_store_area
        CHECK (area_sqft > 0),

    -- Operating hours must be greater than 0
    -- and cannot exceed 24 hours
    CONSTRAINT chk_operating_hours
        CHECK (operating_hours > 0 AND operating_hours <= 24)

);


/* ============================================================
   STEP 3: CREATE ENERGY READINGS TABLE
   ============================================================

   This table stores DAILY measurements for each store.

   Measurements:
   - Electricity consumption
   - Water consumption
   - Diesel consumption
   - Solar generation

   One store can have MANY daily readings.

   Example:

   Store 101
   2026-01-01 -> 7136.05 kWh
   2026-01-02 -> 7021.40 kWh
   2026-01-03 -> 7188.22 kWh

   Primary Key:
   reading_id

   Foreign Key:
   store_id -> stores.store_id

   ============================================================ */

CREATE TABLE IF NOT EXISTS energy_readings (

    -- Unique ID for each reading
    reading_id INT PRIMARY KEY,

    -- Store to which this reading belongs
    store_id INT NOT NULL,

    -- Date of the energy reading
    reading_date DATE NOT NULL,

    -- Electricity consumed in kWh
    electricity_kwh DECIMAL(12,2) NOT NULL,

    -- Water consumed in litres
    water_liters DECIMAL(12,2) NOT NULL,

    -- Diesel consumed in litres
    diesel_liters DECIMAL(10,2) NOT NULL,

    -- Electricity generated by solar panels in kWh
    solar_generation_kwh DECIMAL(12,2) NOT NULL,


    /* --------------------------------------------------------
       FOREIGN KEY

       This ensures that an energy reading can only belong
       to a store that actually exists in the stores table.
       -------------------------------------------------------- */

    CONSTRAINT fk_energy_store
        FOREIGN KEY (store_id)
        REFERENCES stores(store_id),


    /* --------------------------------------------------------
       DATA VALIDATION

       Energy/resource consumption cannot be negative.
       -------------------------------------------------------- */

    CONSTRAINT chk_electricity
        CHECK (electricity_kwh >= 0),

    CONSTRAINT chk_water
        CHECK (water_liters >= 0),

    CONSTRAINT chk_diesel
        CHECK (diesel_liters >= 0),

    CONSTRAINT chk_solar
        CHECK (solar_generation_kwh >= 0),


    /* --------------------------------------------------------
       DUPLICATE PREVENTION

       A store should have only ONE reading for a particular
       date.

       Example:

       Store 101 + 2026-01-01
       cannot appear twice.
       -------------------------------------------------------- */

    CONSTRAINT uq_store_date
        UNIQUE (store_id, reading_date)

);


/* ============================================================
   STEP 4: CREATE UTILITY BILLS TABLE
   ============================================================

   This table stores MONTHLY electricity bills.

   Example:

   Store 101
   January 2026
   Units       = 7086.83 kWh
   Tariff      = ₹X per kWh
   Fixed charge
   Tax
   Total bill

   One store can have MANY monthly bills.

   Primary Key:
   bill_id

   Foreign Key:
   store_id -> stores.store_id

   ============================================================ */

CREATE TABLE IF NOT EXISTS utility_bills (

    -- Unique ID for every bill
    bill_id INT PRIMARY KEY,

    -- Store to which the bill belongs
    store_id INT NOT NULL,

    -- Month for which the bill was generated
    billing_month DATE NOT NULL,

    -- Electricity units mentioned in the bill
    units_kwh DECIMAL(12,2) NOT NULL,

    -- Electricity tariff per kWh
    tariff_per_kwh DECIMAL(8,2) NOT NULL,

    -- Fixed electricity charge
    fixed_charge DECIMAL(10,2) NOT NULL,

    -- Tax amount
    tax_amount DECIMAL(10,2) NOT NULL,

    -- Final bill amount
    total_amount DECIMAL(12,2) NOT NULL,

    -- Payment due date
    due_date DATE NOT NULL,

    -- Payment status
    -- Example: PAID, PENDING, OVERDUE
    payment_status VARCHAR(20) NOT NULL,


    /* --------------------------------------------------------
       FOREIGN KEY

       The store must already exist in the stores table.
       -------------------------------------------------------- */

    CONSTRAINT fk_bill_store
        FOREIGN KEY (store_id)
        REFERENCES stores(store_id),


    /* --------------------------------------------------------
       DATA VALIDATION

       Financial and electricity values cannot be negative.
       -------------------------------------------------------- */

    CONSTRAINT chk_bill_units
        CHECK (units_kwh >= 0),

    CONSTRAINT chk_tariff
        CHECK (tariff_per_kwh >= 0),

    CONSTRAINT chk_fixed_charge
        CHECK (fixed_charge >= 0),

    CONSTRAINT chk_tax
        CHECK (tax_amount >= 0),

    CONSTRAINT chk_total
        CHECK (total_amount >= 0),


    /* --------------------------------------------------------
       DUPLICATE PREVENTION

       A store should have only ONE bill for a particular month.
       -------------------------------------------------------- */

    CONSTRAINT uq_store_billing_month
        UNIQUE (store_id, billing_month)

);


