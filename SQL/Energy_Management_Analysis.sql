-- ------------------------------------------------------------
-- QUERY 3.1: Energy Use Intensity (EUI)
-- ------------------------------------------------------------
-- EUI measures annual electricity consumption per square foot.
--
-- Formula:
-- EUI = Annual Electricity Consumption / Store Area
select * from energy_readings;
select * from stores;

select 
  s.store_id,
    s.store_name,
    s.store_type,
    s.area_sqft,
    round(sum(e.electricity_kwh),2) as ekwh,
round(
sum(e.electricity_kwh)  
/     nullif(s.area_sqft,0),2 ) as eui_s

from stores s join energy_readings e 
on s.store_id = e.store_id
group by   
s.store_id,
    s.store_name,
    s.store_type,
    s.area_sqft
order by eui_s desc
--
-- Lower EUI generally indicates better energy efficiency.
-- ------------------------------------------------------------



SELECT
    s.store_id,
    s.store_name,
    s.store_type,
    s.area_sqft,
    ROUND(SUM(e.electricity_kwh), 2) AS annual_kwh,
    ROUND(
        SUM(e.electricity_kwh) / NULLIF(s.area_sqft, 0),
        2
    ) AS eui_kwh_per_sqft
FROM stores s
JOIN energy_readings e
    ON s.store_id = e.store_id
GROUP BY
    s.store_id,
    s.store_name,
    s.store_type,
    s.area_sqft
ORDER BY eui_kwh_per_sqft DESC;


-- ------------------------------------------------------------
-- QUERY 3.2: Energy Consumption per Operating Hour
-- ------------------------------------------------------------
-- Measures electricity consumption relative to the store's
-- operating hours.
--
-- Useful for comparing stores with different operating schedules.
-- ------------------------------------------------------------

SELECT
    s.store_id,
    s.store_name,
    s.operating_hours,
    ROUND(SUM(e.electricity_kwh), 2) AS annual_kwh,
    ROUND(
        SUM(e.electricity_kwh)
        / NULLIF(SUM(s.operating_hours), 0),
        2
    ) AS kwh_per_operating_hour
FROM stores s
JOIN energy_readings e
    ON s.store_id = e.store_id
GROUP BY
    s.store_id,
    s.store_name,
    s.operating_hours
ORDER BY kwh_per_operating_hour DESC;


-- ------------------------------------------------------------
-- QUERY 3.3: Energy Efficiency Ranking
-- ------------------------------------------------------------
-- Rank stores according to EUI.
--
-- Rank 1 = highest EUI and therefore a priority for
-- energy-efficiency investigation.
-- ------------------------------------------------------------

WITH store_eui AS (
    SELECT
        s.store_id,
        s.store_name,
        s.store_type,
        s.area_sqft,
        SUM(e.electricity_kwh) AS annual_kwh
    FROM stores s
    JOIN energy_readings e
        ON s.store_id = e.store_id
    GROUP BY
        s.store_id,
        s.store_name,
        s.store_type,
        s.area_sqft
)
SELECT
    store_id,
    store_name,
    store_type,
    ROUND(annual_kwh, 2) AS annual_kwh,
    ROUND(annual_kwh / NULLIF(area_sqft, 0), 2) AS eui,
    RANK() OVER (
        ORDER BY annual_kwh / NULLIF(area_sqft, 0) DESC
    ) AS efficiency_priority_rank
FROM store_eui
ORDER BY efficiency_priority_rank;


-- ============================================================
-- BATCH 4: CO2 & SUSTAINABILITY ANALYTICS
-- ============================================================
-- Objective:
-- Measure carbon emissions associated with electricity usage
-- and quantify the contribution of solar generation.
--
-- Emission factor used:
-- 0.710 kg CO2 per kWh
-- ============================================================


-- ------------------------------------------------------------
-- QUERY 4.1: Store-Level CO2 Emissions
-- ------------------------------------------------------------
-- Formula:
-- CO2 = Electricity Consumption × Emission Factor
-- ------------------------------------------------------------

SELECT
    s.store_id,
    s.store_name,
    ROUND(SUM(e.electricity_kwh), 2) AS annual_kwh,
    ROUND(
        SUM(e.electricity_kwh) * 0.710,
        2
    ) AS co2_kg,
    ROUND(
        SUM(e.electricity_kwh) * 0.710 / 1000,
        2
    ) AS co2_tonnes
FROM stores s
JOIN energy_readings e
    ON s.store_id = e.store_id
GROUP BY
    s.store_id,
    s.store_name
ORDER BY co2_tonnes DESC;


-- ------------------------------------------------------------
-- QUERY 4.2: Solar Generation and Carbon Reduction Potential
-- ------------------------------------------------------------
-- Estimates the electricity contribution from solar and
-- the associated avoided grid-emission potential.
-- ------------------------------------------------------------

SELECT
    s.store_id,
    s.store_name,
    ROUND(SUM(e.solar_generation_kwh), 2)
        AS solar_generation_kwh,

    ROUND(
        SUM(e.solar_generation_kwh)
        / NULLIF(SUM(e.electricity_kwh), 0) * 100,
        2
    ) AS solar_contribution_percent,

    ROUND(
        SUM(e.solar_generation_kwh) * 0.710,
        2
    ) AS potential_co2_avoided_kg

FROM stores s
JOIN energy_readings e
    ON s.store_id = e.store_id

GROUP BY
    s.store_id,
    s.store_name

ORDER BY potential_co2_avoided_kg DESC;


-- ------------------------------------------------------------
-- QUERY 4.3: Overall Sustainability KPI
-- ------------------------------------------------------------
-- Provides portfolio-level electricity, solar and emissions.
-- ------------------------------------------------------------

SELECT
    ROUND(SUM(e.electricity_kwh), 2)
        AS total_electricity_kwh,

    ROUND(SUM(e.solar_generation_kwh), 2)
        AS total_solar_kwh,

    ROUND(
        SUM(e.solar_generation_kwh)
        / NULLIF(SUM(e.electricity_kwh), 0) * 100,
        2
    ) AS solar_contribution_percent,

    ROUND(
        SUM(e.electricity_kwh) * 0.710 / 1000,
        2
    ) AS total_co2_tonnes

FROM energy_readings e;


-- ============================================================
-- BATCH 5: ENERGY ANOMALY DETECTION
-- ============================================================
-- Objective:
-- Identify unusually high daily electricity consumption.
--
-- Method:
-- Compare each reading against the store's average and
-- standard deviation.
--
-- A reading more than 2 standard deviations above the
-- store's average is flagged as an anomaly.
-- ============================================================


-- ------------------------------------------------------------
-- QUERY 5.1: Store-Level Daily Consumption Anomalies
-- ------------------------------------------------------------

WITH store_statistics AS (
    SELECT
        store_id,
        AVG(electricity_kwh) AS avg_kwh,
        STDDEV(electricity_kwh) AS std_kwh
    FROM energy_readings
    GROUP BY store_id
)
SELECT
    e.store_id,
    s.store_name,
    e.reading_date,
    e.electricity_kwh,
    ROUND(st.avg_kwh, 2) AS avg_daily_kwh,
    ROUND(
        (e.electricity_kwh - st.avg_kwh)
        / NULLIF(st.std_kwh, 0),
        2
    ) AS z_score
FROM energy_readings e
JOIN store_statistics st
    ON e.store_id = st.store_id
JOIN stores s
    ON e.store_id = s.store_id
WHERE
    e.electricity_kwh >
    st.avg_kwh + (2 * st.std_kwh)
ORDER BY z_score DESC;


-- ------------------------------------------------------------
-- QUERY 5.2: Count Anomalies by Store
-- ------------------------------------------------------------
-- Identifies stores with the highest number of unusual
-- consumption events.
-- ------------------------------------------------------------

WITH store_statistics AS (
    SELECT
        store_id,
        AVG(electricity_kwh) AS avg_kwh,
        STDDEV(electricity_kwh) AS std_kwh
    FROM energy_readings
    GROUP BY store_id
)
SELECT
    s.store_id,
    s.store_name,
    COUNT(*) AS anomaly_count
FROM energy_readings e
JOIN store_statistics st
    ON e.store_id = st.store_id
JOIN stores s
    ON e.store_id = s.store_id
WHERE
    e.electricity_kwh >
    st.avg_kwh + (2 * st.std_kwh)
GROUP BY
    s.store_id,
    s.store_name
ORDER BY anomaly_count DESC;


-- ============================================================
-- BATCH 6: STORE BENCHMARKING
-- ============================================================
-- Objective:
-- Compare stores against other stores of the same type.
--
-- This is more meaningful than comparing every store together,
-- because a hypermarket naturally consumes more energy than
-- a small convenience store.
-- ============================================================


-- ------------------------------------------------------------
-- QUERY 6.1: Store EUI vs Store-Type Average
-- ------------------------------------------------------------

WITH store_eui AS (
    SELECT
        s.store_id,
        s.store_name,
        s.store_type,
        s.area_sqft,
        SUM(e.electricity_kwh) / NULLIF(s.area_sqft, 0)
            AS eui
    FROM stores s
    JOIN energy_readings e
        ON s.store_id = e.store_id
    GROUP BY
        s.store_id,
        s.store_name,
        s.store_type,
        s.area_sqft
),
type_average AS (
    SELECT
        store_type,
        AVG(eui) AS avg_type_eui
    FROM store_eui
    GROUP BY store_type
)
SELECT
    se.store_id,
    se.store_name,
    se.store_type,
    ROUND(se.eui, 2) AS store_eui,
    ROUND(ta.avg_type_eui, 2) AS store_type_avg_eui,

    ROUND(
        (se.eui - ta.avg_type_eui)
        / NULLIF(ta.avg_type_eui, 0) * 100,
        2
    ) AS variance_from_benchmark_percent

FROM store_eui se
JOIN type_average ta
    ON se.store_type = ta.store_type

ORDER BY variance_from_benchmark_percent DESC;


-- ------------------------------------------------------------
-- QUERY 6.2: Best and Worst Stores by EUI
-- ------------------------------------------------------------
-- Gives a simple performance classification.
-- ------------------------------------------------------------

WITH store_eui AS (
    SELECT
        s.store_id,
        s.store_name,
        s.store_type,
        SUM(e.electricity_kwh)
        / NULLIF(s.area_sqft, 0) AS eui
    FROM stores s
    JOIN energy_readings e
        ON s.store_id = e.store_id
    GROUP BY
        s.store_id,
        s.store_name,
        s.store_type,
        s.area_sqft
)
SELECT
    store_id,
    store_name,
    store_type,
    ROUND(eui, 2) AS eui,

    CASE
        WHEN eui <= (
            SELECT AVG(eui) FROM store_eui
        )
        THEN 'Better than average'
        ELSE 'Needs improvement'
    END AS performance_category

FROM store_eui
ORDER BY eui DESC;


-- ============================================================
-- BATCH 7: ENERGY COST OPTIMIZATION & SAVINGS
-- ============================================================
-- Objective:
-- Estimate potential savings if high-consuming stores
-- reduce electricity consumption.
--
-- Assumption:
-- Potential reduction = 10%
--
-- This is a scenario estimate, NOT actual guaranteed savings.
-- ============================================================


-- ------------------------------------------------------------
-- QUERY 7.1: Potential Electricity Cost Savings
-- ------------------------------------------------------------
-- Formula:
-- Potential Savings =
-- Current Energy Cost × 10%
-- ------------------------------------------------------------

SELECT
    s.store_id,
    s.store_name,

    ROUND(SUM(b.units_kwh), 2)
        AS billed_kwh,

    ROUND(SUM(b.total_amount), 2)
        AS current_cost,

    ROUND(SUM(b.total_amount) * 0.10, 2)
        AS potential_savings_10_percent,

    ROUND(SUM(b.total_amount) * 0.90, 2)
        AS estimated_cost_after_savings

FROM stores s
JOIN utility_bills b
    ON s.store_id = b.store_id

GROUP BY
    s.store_id,
    s.store_name

ORDER BY potential_savings_10_percent DESC;


-- ------------------------------------------------------------
-- QUERY 7.2: Portfolio-Level Savings Opportunity
-- ------------------------------------------------------------
-- Estimates the total possible savings across all stores.
-- ------------------------------------------------------------

SELECT
    ROUND(SUM(total_amount), 2)
        AS current_total_cost,

    ROUND(SUM(total_amount) * 0.10, 2)
        AS potential_savings_10_percent,

    ROUND(SUM(total_amount) * 0.90, 2)
        AS estimated_cost_after_savings

FROM utility_bills;


-- ------------------------------------------------------------
-- QUERY 7.3: Identify Priority Stores for Energy Audits
-- ------------------------------------------------------------
-- Priority stores are those with:
-- 1. High EUI
-- 2. High total cost
--
-- These stores are strong candidates for facility/energy audits.
-- ------------------------------------------------------------

WITH store_eui AS (
    SELECT
        s.store_id,
        s.store_name,
        s.store_type,
        SUM(e.electricity_kwh)
        / NULLIF(s.area_sqft, 0) AS eui
    FROM stores s
    JOIN energy_readings e
        ON s.store_id = e.store_id
    GROUP BY
        s.store_id,
        s.store_name,
        s.store_type,
        s.area_sqft
),
store_cost AS (
    SELECT
        store_id,
        SUM(total_amount) AS total_cost
    FROM utility_bills
    GROUP BY store_id
)
SELECT
    se.store_id,
    se.store_name,
    se.store_type,
    ROUND(se.eui, 2) AS eui,
    ROUND(sc.total_cost, 2) AS total_cost
FROM store_eui se
JOIN store_cost sc
    ON se.store_id = sc.store_id
ORDER BY
    se.eui DESC,
    sc.total_cost DESC
LIMIT 10;


-- ============================================================
-- BATCH 8: ADVANCED MANAGEMENT ANALYTICS
-- ============================================================
-- Objective:
-- Produce management-level KPIs and identify consumption
-- trends that can later be visualized in Power BI.
-- ============================================================


-- ------------------------------------------------------------
-- QUERY 8.1: Monthly Electricity Consumption Trend
-- ------------------------------------------------------------
-- Shows month-over-month electricity consumption.
-- ------------------------------------------------------------

WITH monthly_usage AS (
    SELECT
        YEAR(reading_date) AS year,
        MONTH(reading_date) AS month,
        SUM(electricity_kwh) AS monthly_kwh
    FROM energy_readings
    GROUP BY
        YEAR(reading_date),
        MONTH(reading_date)
)
SELECT
    year,
    month,
    ROUND(monthly_kwh, 2) AS monthly_kwh,

    ROUND(
        LAG(monthly_kwh) OVER (
            ORDER BY year, month
        ),
        2
    ) AS previous_month_kwh,

    ROUND(
        (
            monthly_kwh -
            LAG(monthly_kwh) OVER (
                ORDER BY year, month
            )
        )
        / NULLIF(
            LAG(monthly_kwh) OVER (
                ORDER BY year, month
            ),
            0
        ) * 100,
        2
    ) AS month_over_month_change_percent

FROM monthly_usage
ORDER BY year, month;


-- ------------------------------------------------------------
-- QUERY 8.2: Monthly Cost + Energy KPI
-- ------------------------------------------------------------
-- Combines electricity consumption and utility cost
-- into one management-level view.
-- ------------------------------------------------------------

SELECT
    YEAR(b.billing_month) AS year,
    MONTH(b.billing_month) AS month,

    ROUND(SUM(b.units_kwh), 2)
        AS billed_kwh,

    ROUND(SUM(b.total_amount), 2)
        AS total_cost,

    ROUND(
        SUM(b.total_amount)
        / NULLIF(SUM(b.units_kwh), 0),
        2
    ) AS effective_cost_per_kwh

FROM utility_bills b

GROUP BY
    YEAR(b.billing_month),
    MONTH(b.billing_month)

ORDER BY
    year,
    month;


-- ------------------------------------------------------------
-- QUERY 8.3: Executive Energy KPI Summary
-- ------------------------------------------------------------
-- Produces the major portfolio-level KPIs in one result.
--
-- This result can later become the basis for Power BI
-- executive dashboard cards.
-- ------------------------------------------------------------

SELECT

    -- Total stores
    (SELECT COUNT(*)
     FROM stores) AS total_stores,

    -- Total electricity consumption
    (SELECT ROUND(SUM(electricity_kwh), 2)
     FROM energy_readings) AS total_electricity_kwh,

    -- Total water consumption
    (SELECT ROUND(SUM(water_liters), 2)
     FROM energy_readings) AS total_water_liters,

    -- Total diesel consumption
    (SELECT ROUND(SUM(diesel_liters), 2)
     FROM energy_readings) AS total_diesel_liters,

    -- Total solar generation
    (SELECT ROUND(SUM(solar_generation_kwh), 2)
     FROM energy_readings) AS total_solar_kwh,

    -- Total utility cost
    (SELECT ROUND(SUM(total_amount), 2)
     FROM utility_bills) AS total_utility_cost,

    -- Total CO2 emissions
    (SELECT ROUND(SUM(electricity_kwh) * 0.710 / 1000, 2)
     FROM energy_readings) AS total_co2_tonnes,

    -- Solar contribution
    (SELECT ROUND(
        SUM(solar_generation_kwh)
        / NULLIF(SUM(electricity_kwh), 0) * 100,
        2
    )
     FROM energy_readings) AS solar_contribution_percent;